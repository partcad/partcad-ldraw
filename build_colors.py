# The finishes LDraw draws, with a 3D view's roughness and metallic for each.
FINISHES = {
    "chrome": {"name": "Chrome", "roughness": 0.05, "metallic": 1.0},
    "pearlescent": {"name": "Pearlescent", "roughness": 0.35, "metallic": 0.6},
    "metallic": {"name": "Metallic", "roughness": 0.3, "metallic": 0.8},
    "matte-metallic": {"name": "Matte Metallic", "roughness": 0.6, "metallic": 0.6},
    "glitter": {"name": "Glitter", "roughness": 0.3, "metallic": 0.2},
    "speckle": {"name": "Speckle", "roughness": 0.5, "metallic": 0.3},
}

_LEGOID = re.compile(r"^0\s+//\s*LEGOID\s+(\d+(?:\s*/\s*\d+)*)\s*-\s*(.+?)\s*$")
_COLOUR = re.compile(r"^0\s+!COLOUR\s+(\S+)\s+CODE\s+(\d+)\s+VALUE\s+(#[0-9A-Fa-f]{6})\s+EDGE\s+\S+(.*)$")


def parse(text):
    """Every colour of 'LDConfig.ldr', in the order it lists them, with the LEGO ids above it."""
    colours = []
    lego = None
    for line in text.splitlines():
        line = line.strip()
        match = _LEGOID.match(line)
        if match:
            lego = ([part.strip() for part in match.group(1).split("/")], match.group(2))
            continue
        match = _COLOUR.match(line)
        if match:
            rest = match.group(4).split()
            alpha = 255
            if "ALPHA" in rest:
                alpha = int(rest[rest.index("ALPHA") + 1])
            keywords = set(word for word in rest if word.isupper() and not word.isdigit())
            if "MATERIAL" in rest:
                keywords.add(rest[rest.index("MATERIAL") + 1])
            colours.append(
                {
                    "ldraw": match.group(1),
                    "code": match.group(2),
                    "value": match.group(3).upper(),
                    "alpha": alpha,
                    "keywords": keywords,
                    "lego": lego,
                }
            )
            lego = None
            continue
        if line and not line.startswith("0 //"):
            # A LEGO id belongs to the colour right below it, and to nothing
            # further down.
            lego = None
    return colours


def material_and_finish(colour):
    keywords = colour["keywords"]
    finish = next((FINISH_KEYWORDS[k] for k in sorted(keywords) if k in FINISH_KEYWORDS), None)
    if "RUBBER" in keywords:
        material = "rubber"
    elif "FABRIC" in keywords:
        material = "fabric"
    elif colour["alpha"] < 255:
        material = "polycarbonate"
    else:
        material = "abs"
    return material, finish


def build(colours):
    """'(colors, table)': the declarations, and what every code is."""
    lego_names = {}
    for colour in colours:
        if colour["lego"]:
            lego_names.setdefault(colour["lego"][1], []).append(colour)

    declared = {}
    by_value = {}
    for colour in colours:
        if not colour["lego"]:
            continue
        ids, name = colour["lego"]
        if len(lego_names[name]) > 1:
            # Two LEGO colours LEGO names alike: told apart by their ids.
            name = "%s (LEGO %s)" % (name, ids[0])
        display = colour["value"] + ("%02X" % colour["alpha"] if colour["alpha"] < 255 else "")
        declaration = {
            "desc": "LEGO colour %s; LDraw %s (code %s)" % (" / ".join(ids), colour["ldraw"], colour["code"]),
            "display": display,
            "ids": {"lego": ids if len(ids) > 1 else ids[0], "ldraw": colour["code"]},
        }
        alias = colour["ldraw"].replace("_", " ")
        declaration["_alias"] = alias
        declared[name] = declaration
        colour["declared"] = name
        if "RUBBER" not in colour["keywords"]:
            by_value.setdefault((colour["value"], colour["alpha"]), colour)

    for colour in colours:
        if colour["lego"]:
            continue
        twin = by_value.get((colour["value"], colour["alpha"])) if "RUBBER" in colour["keywords"] else None
        if twin is not None:
            # LEGO's colour, in rubber: the twin's colour declaration says it.
            colour["declared"] = twin["declared"]
            colour["twin"] = twin["code"]
            continue
        name = colour["ldraw"].replace("_", " ")
        if name in declared:
            name = "%s (LDraw %s)" % (name, colour["code"])
        declared[name] = {
            "desc": "LDraw %s (code %s), which LEGO has no id for: drawn, and claimed by nothing"
            % (
                colour["ldraw"],
                colour["code"],
            ),
            "display": colour["value"] + ("%02X" % colour["alpha"] if colour["alpha"] < 255 else ""),
            "ids": {"ldraw": colour["code"]},
            "manufacturable": False,
        }
        colour["declared"] = name

    # An LDraw name is an alias where it names nothing else.
    names = set(declared)
    for name, declaration in declared.items():
        alias = declaration.pop("_alias", None)
        if alias and alias != name and alias not in names:
            declaration["aliases"] = [alias]
            names.add(alias)

    table = {}
    for colour in colours:
        material, finish = material_and_finish(colour)
        rgb = colour["value"]
        table[colour["code"]] = {
            # The code its colour declaration answers to under 'ids: {ldraw:}'.
            "color": colour.get("twin", colour["code"]),
            "material": material,
            "finish": finish,
            "rgba": [int(rgb[1:3], 16), int(rgb[3:5], 16), int(rgb[5:7], 16), round(colour["alpha"] / 255.0, 4)],
            # The declarations themselves, by name, for what names them outright:
            # a shortcut's link to a part its file draws in this code.
            "names": {
                "color": colour["declared"],
                "material": MATERIALS[material]["name"],
                "finish": FINISHES[finish]["name"] if finish else None,
            },
        }
    return declared, table


def _quoted(text):
    return json.dumps(text, ensure_ascii=False)


def yaml_block(declared):
    """The generated sections of 'partcad.yaml', written by hand so that it reads as the rest of the file does."""
    lines = [BEGIN, "colors:"]
    for name in sorted(declared, key=str.casefold):
        declaration = declared[name]
        lines.append("  %s:" % _quoted(name))
        lines.append("    desc: %s" % _quoted(declaration["desc"]))
        lines.append("    display: %s" % _quoted("#" + declaration["display"].lstrip("#")))
        ids = ", ".join("%s: %s" % (system, json.dumps(value)) for system, value in sorted(declaration["ids"].items()))
        lines.append("    ids: {%s}" % ids)
        if declaration.get("aliases"):
            lines.append("    aliases: [%s]" % ", ".join(_quoted(alias) for alias in declaration["aliases"]))
        if declaration.get("manufacturable") is False:
            lines.append("    manufacturable: false")
    lines.append("materials:")
    for key in sorted(MATERIALS):
        material = MATERIALS[key]
        lines.append("  %s:" % _quoted(material["name"]))
        lines.append("    desc: %s" % _quoted(material["desc"]))
        if "density" in material:
            lines.append("    density: %d" % material["density"])
        for field, value, source in material.get("analysis", ()):
            lines.append("    %s: %s # %s" % (field, value, source))
        lines.append("    ids: {ldraw: %s}" % _quoted(key))
    lines.append("finishes:")
    for key in sorted(FINISHES):
        finish = FINISHES[key]
        lines.append("  %s:" % _quoted(finish["name"]))
        lines.append("    display: {roughness: %s, metallic: %s}" % (finish["roughness"], finish["metallic"]))
        lines.append("    ids: {ldraw: %s}" % _quoted(key))
    lines.append(END)
    return "\n".join(lines) + "\n"


def write(config_path, table_path, text):
    declared, table = build(parse(text))
    with open(config_path, encoding="utf-8") as stream:
        config = stream.read()
    block = yaml_block(declared)
    if BEGIN in config:
        start = config.index(BEGIN)
        end = config.index(END, start) + len(END) + 1
        config = config[:start] + block + config[end:]
    else:
        config = config.rstrip("\n") + "\n\n" + block
    with open(config_path, "w", encoding="utf-8") as stream:
        stream.write(config)
    with open(table_path, "w", encoding="utf-8") as stream:
        json.dump(table, stream, indent=1, sort_keys=True)
        stream.write("\n")
    return declared, table


def main(argv):
    if len(argv) > 1:
        with open(argv[1], encoding="utf-8") as stream:
            text = stream.read()
    else:
        with urllib.request.urlopen(LDCONFIG_URL, timeout=60) as response:
            text = response.read().decode("utf-8")
    declared, table = write("partcad.yaml", "ldraw_colors.json", text)
    claimed = sum(1 for d in declared.values() if d.get("manufacturable") is not False)
    print("%d colours (%d LEGO's), %d codes" % (len(declared), claimed, len(table)))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
