"""Build LEGO's colours, materials and finishes from LDraw's colour table.

LDraw's 'LDConfig.ldr' lists every colour code a part may be drawn in, with its
value, its finish (CHROME, PEARLESCENT, METAL, RUBBER, ...) and, for the colours
LEGO makes, LEGO's own id and name in a comment above it:

    0                              // LEGOID 194 - Medium Stone Grey
    0 !COLOUR Light_Bluish_Grey      CODE    71   VALUE #969696   EDGE #333333

An LDraw code is a colour, a material and a finish at once: 71 is Medium Stone
Grey in ABS, 256 is LEGO's black in rubber, 334 is a chrome gold. This script
writes the two halves of that (docs/design/cmf.md in PartCAD, section 10):

- the package's 'colors:', 'materials:' and 'finishes:', between the markers in
  'partcad.yaml': a colour per LEGO id, named as LEGO names it, with 'ids' for
  LEGO and LDraw and LDraw's value as its 'display'; the materials and finishes
  the codes imply. A colour LEGO has no id for is declared too, under LDraw's
  name, as 'manufacturable: false': it draws, and claims nothing.
- 'ldraw_colors.json', which the 'ldraw' part type reads: for every code, the
  colour, material and finish it is, by those declarations' 'ids', for PartCAD's
  'ldraw' convention to convert (see 'ldraw.py', '_cmf').

A rubber code has no LEGO id of its own: it is the solid colour of the same
value, in rubber, and is written as that colour with the material 'rubber'.

Run it from the package directory when LDraw publishes a new 'LDConfig.ldr':

    python build_colors.py [LDConfig.ldr]

With no path it is fetched from the library. The output is sorted and written
the same way every time, so a run that changes nothing changes no file.
"""

